"""结构化薪资区间跨城市平滑（设计文档 §4.5 补充）。

跨源薪资异常判定需要同一城市口径下比较：同岗位分组内混入一线城市 JD
（高薪）与二线城市 JD（低薪）时，max/min > 1.5 会把二线城市 JD 误判
为「低薪异常」。本模块提供城市 → 薪资水平指数（一线=1.0 基准）映射，
校验前将月薪按城市指数归一化（salary / index），把跨城市正常薪资差
平滑掉，仅在同一城市口径下凸显真正的异常。

指数口径说明：一线城市 1.0；新一线 0.82~0.90；二线 0.72~0.82；三线及
以下 0.68~0.72。数值为同岗位跨城市薪资水平的近似比例（供平滑比较，
非精确统计口径）。未收录城市回退 1.0（不改变原有判定，避免误平滑）。
"""

import re

# 城市 → 薪资水平指数（一线 1.0 基准，数值越大薪资水平越高）
_CITY_TIER_INDEX: dict[str, float] = {
    # ── 一线 ──
    "北京": 1.00, "上海": 1.00, "深圳": 1.02, "广州": 0.98,
    # ── 新一线（0.82~0.90）──
    "杭州": 0.90, "成都": 0.88, "南京": 0.88, "苏州": 0.86, "武汉": 0.85,
    "天津": 0.84, "重庆": 0.82, "西安": 0.82, "宁波": 0.82, "合肥": 0.82,
    "厦门": 0.82, "无锡": 0.82, "青岛": 0.80, "长沙": 0.80, "郑州": 0.76,
    "沈阳": 0.76, "昆明": 0.74,
    # ── 二线（0.72~0.80）──
    "大连": 0.76, "福州": 0.78, "济南": 0.76, "东莞": 0.78, "佛山": 0.78,
    "哈尔滨": 0.72, "长春": 0.70, "石家庄": 0.72, "南昌": 0.72, "贵阳": 0.72,
    "南宁": 0.70, "太原": 0.70, "兰州": 0.70, "银川": 0.68, "呼和浩特": 0.68,
    "乌鲁木齐": 0.70, "海口": 0.74,
}

# 未收录城市（含国际地点）回退指数：不影响原有判定（默认 1.0）
DEFAULT_CITY_INDEX = 1.0

# 按名称长度降序，子串匹配时优先命中更长城市名（如「广州市」优先于「广州」）
_CITY_NAMES = sorted(_CITY_TIER_INDEX, key=len, reverse=True)

# location 分隔符：中文间隔号 / 顿号 / 逗号 / 空格
_LOCATION_SEP = re.compile(r"[·,，、/|]")


def extract_city(location: str | None) -> str:
    """从 location 文本提取城市名。

    - 已知城市子串匹配（如「北京·朝阳区」→「北京」、「成都 高新区」→「成都」）；
    - 未知城市取首个分隔片段（英文地点/区县名等），长度截断 32。
    """
    if not location:
        return ""
    text = location.strip()
    if not text:
        return ""
    for name in _CITY_NAMES:
        if name in text:
            return name
    return _LOCATION_SEP.split(text, maxsplit=1)[0].strip()[:32]


def city_index(city: str) -> float:
    """返回城市薪资水平指数；未收录城市回退 1.0。"""
    return _CITY_TIER_INDEX.get(city, DEFAULT_CITY_INDEX)
